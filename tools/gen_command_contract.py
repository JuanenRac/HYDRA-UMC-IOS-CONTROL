"""Writes the robot command constants of the app from docs/robot_command_contract.json.

    python tools/gen_command_contract.py           # writes lib/models/robot_command_contract.dart
    python tools/gen_command_contract.py --check   # exit 1 when the file is not what the contract gives
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / "docs" / "robot_command_contract.json"
TARGET = ROOT / "lib" / "models" / "robot_command_contract.dart"
FEATURES = ROOT / "docs" / "ios_feature_contract.json"
FEATURES_TARGET = ROOT / "lib" / "models" / "ios_feature_contract.dart"


def dart_number(value: float) -> str:
    return f"{float(value)}"


def render(contract: dict) -> str:
    commands = contract["commands"]
    limits = contract["limits"]
    home = contract["homeReset"]
    link = contract["linkHealth"]

    def camel(constant: str) -> str:
        head, *rest = constant.lower().split("_")
        return head + "".join(part.capitalize() for part in rest)

    lines = [
        "// =============================================================================",
        "// HYDRA-UMC CONTROL (iOS/Flutter) - models/robot_command_contract.dart",
        "// Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
        "// GPL-3.0-or-later - see LICENSE",
        "// =============================================================================",
        "// Generated by tools/gen_command_contract.py from docs/robot_command_contract.json. Do not edit by hand.",
        "",
        "/// The control commands of POST /api/robot/{id}/command and the limits the server enforces on them.",
        "class RobotCommandContract {",
        "  RobotCommandContract._();",
        "",
        f"  static const int protocolVersion = {int(contract['protocolVersion'])};",
        "",
    ]
    for command in commands:
        lines.append(f"  static const String {camel(command['constant'])} = '{command['name']}';")
    names = lambda items: ", ".join(camel(c["constant"]) for c in items)  # noqa: E731
    lines += [
        "",
        f"  static const Set<String> all = {{{names(commands)}}};",
        "",
        "  /// The commands the server orders by number (`seq`).",
        f"  static const Set<String> numbered = {{{names([c for c in commands if c['numbered']])}}};",
        "",
        "  /// The commands sent over and over while a control is held; they carry no If-Match in the standard mode.",
        f"  static const Set<String> continuous = {{{names([c for c in commands if c['continuous']])}}};",
        "",
        f"  static const double speedMin = {dart_number(limits['speedMin'])};",
        f"  static const double speedMax = {dart_number(limits['speedMax'])};",
        f"  static const double jogMaxAmount = {dart_number(limits['jogMaxAmount'])};",
        f"  static const double jogStepMax = {dart_number(limits['jogStepMax'])};",
        f"  static const int outputIndexMax = {int(limits['outputIndexMax'])};",
        "",
        "  /// HOME/RESET: off until the person turns it on; how many confirmations it asks and how long they stay valid.",
        f"  static const bool homeResetEnabledByDefault = {'true' if home['enabledByDefault'] else 'false'};",
        f"  static const int homeResetConfirmSteps = {int(home['confirmSteps'])};",
        f"  static const int homeResetConfirmWindowMs = {int(home['confirmWindowMs'])};",
        "",
        "  /// Link health: round-trip times (ms) that grade the link to the server, and how long without an answer counts as lost.",
        f"  static const bool linkIndicatorEnabledByDefault = {'true' if link['indicatorEnabledByDefault'] else 'false'};",
        f"  static const int linkProbeIntervalMs = {int(link['probeIntervalMs'])};",
        f"  static const int linkProbeTimeoutMs = {int(link['probeTimeoutMs'])};",
        f"  static const int linkSampleWindow = {int(link['sampleWindow'])};",
        f"  static const int linkGoodRttMs = {int(link['goodRttMs'])};",
        f"  static const int linkPoorRttMs = {int(link['poorRttMs'])};",
        f"  static const int linkBlockRttMs = {int(link['blockRttMs'])};",
        f"  static const int linkLostAfterMs = {int(link['lostAfterMs'])};",
        "}",
        "",
    ]
    return "\n".join(lines)


def render_features(contract: dict) -> str:
    """lib/models/ios_feature_contract.dart: one class per section of docs/ios_feature_contract.json."""
    lines = [
        "// =============================================================================",
        "// HYDRA-UMC CONTROL (iOS/Flutter) - models/ios_feature_contract.dart",
        "// Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
        "// GPL-3.0-or-later - see LICENSE",
        "// =============================================================================",
        "// Generated by tools/gen_command_contract.py from docs/ios_feature_contract.json. Do not edit by hand.",
        "",
    ]
    for section, values in contract.items():
        if not isinstance(values, dict):
            continue
        cls = section[0].upper() + section[1:] + "Contract"
        lines += [f"/// Settings of the `{section}` section.", f"class {cls} {{", f"  {cls}._();", ""]
        for key, value in values.items():
            if key == "note":
                continue
            if isinstance(value, bool):
                lines.append(f"  static const bool {key} = {'true' if value else 'false'};")
            else:
                lines.append(f"  static const int {key} = {int(value)};")
        lines += ["}", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    names = [c["name"] for c in contract["commands"]]
    if len(set(names)) != len(names):
        print("docs/robot_command_contract.json: a command is listed twice")
        return 1
    features = json.loads(FEATURES.read_text(encoding="utf-8"))
    outputs = (
        (TARGET, render(contract), "robot_command_contract"),
        (FEATURES_TARGET, render_features(features), "ios_feature_contract"),
    )
    if "--check" in argv:
        for target, text, name in outputs:
            current = target.read_text(encoding="utf-8") if target.is_file() else ""
            if current.replace("\r\n", "\n") != text:
                print(f"{target.relative_to(ROOT).as_posix()} does not match docs/{name}.json: run tools/gen_command_contract.py")
                return 1
        return 0
    for target, text, _ in outputs:
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
